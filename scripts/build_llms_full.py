"""Regenerate llms-full.txt: every user-facing document flattened into one Markdown file.

    python scripts/build_llms_full.py
"""

from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "ast_pack"


def module_doc(name: str) -> str:
    tree = ast.parse((SRC / name).read_text("utf-8"))
    return (ast.get_docstring(tree) or "").strip()


def schema_summary() -> str:
    schema = json.loads((ROOT / "schema.json").read_text("utf-8"))
    lines = [schema["description"], ""]
    for name, d in schema["$defs"].items():
        props = d.get("properties", {})
        if not props:
            continue
        lines.append(f"### `{name}`")
        lines.append("")
        for key, spec in props.items():
            desc = spec.get("description", "")
            typ = spec.get("type") or ("enum: " + ", ".join(map(str, spec["enum"])) if "enum" in spec else "")
            if "const" in spec:
                typ = f"const {spec['const']!r}"
            if "$ref" in spec:
                typ = spec["$ref"].rsplit("/", 1)[-1]
            if spec.get("type") == "array" and "$ref" in spec.get("items", {}):
                typ = f"array of {spec['items']['$ref'].rsplit('/', 1)[-1]}"
            lines.append(f"- `{key}` ({typ}){': ' + desc if desc else ''}")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parts = [
        "# ast-pack — complete documentation (single file for LLMs and AI agents)",
        "",
        "> Source: https://github.com/ginckl/ast-pack · generated by scripts/build_llms_full.py from README.md, "
        "AGENT_GUIDE.md, benchmarks/RESULTS.md, schema.json and module docstrings.",
        "",
        "---",
        "",
        (ROOT / "README.md").read_text("utf-8").strip(),
        "",
        "---",
        "",
        (ROOT / "AGENT_GUIDE.md").read_text("utf-8").strip(),
        "",
        "---",
        "",
        "# JSON output contract (schema.json)",
        "",
        schema_summary(),
        "---",
        "",
        "# Internals",
        "",
    ]
    for title, mod in [
        ("Command-line interface", "cli.py"),
        ("Engine", "engine.py"),
        ("Entry-point resolution", "entry.py"),
        ("Repository index and resolver", "index.py"),
        ("Graph walk", "slicer.py"),
        ("Rendering", "render.py"),
        ("Token counting", "tokens.py"),
        ("File discovery", "scanner.py"),
        ("Extractors", "extractors/base.py"),
        ("HTTP and WebSocket server", "server.py"),
        ("MCP server", "mcp.py"),
    ]:
        parts += [f"## {title} (`src/ast_pack/{mod}`)", "", module_doc(mod), ""]
    parts += ["---", "", (ROOT / "benchmarks" / "RESULTS.md").read_text("utf-8").strip(), ""]
    (ROOT / "llms-full.txt").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {ROOT / 'llms-full.txt'}")


if __name__ == "__main__":
    main()
